import type { ReactNode } from "react";

// Ícones simples em SVG (herdam a cor do texto via currentColor).
// Evita instalar uma biblioteca de ícones só para a Home.
interface IconProps {
  size?: number;
}

function Icon({ size = 20, children }: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

